// Static site generator for dycprojects.com.au
// Pre-renders each React page to static HTML (for speed + SEO), then hydrates it in the
// browser so menus and tabs stay interactive. Run from the repo root: `npm run build`.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();
const cfg = JSON.parse(fs.readFileSync(path.join(root, "site.config.json"), "utf8"));
const base = cfg.baseUrl.replace(/\/$/, "");
const tmp = path.join(root, ".build");
const version = Date.now().toString(36);

fs.rmSync(tmp, { recursive: true, force: true });
fs.mkdirSync(tmp, { recursive: true });
fs.rmSync(path.join(root, "assets/js"), { recursive: true, force: true });

// 0. Inline the Material Symbols used by <Icon name="…"> into a generated module
{
  const used = new Set();
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(jsx?|mjs)$/.test(e.name))
        {
          const src = fs.readFileSync(p, "utf8");
          // <Icon name="x">, data objects { icon: "x" }, and tuple arrays [["x", …], …] in files that render <Icon>
          for (const m of src.matchAll(/<Icon\s+name="([a-z0-9_]+)"|\bicon:\s*"([a-z0-9_]+)"/g)) used.add(m[1] || m[2]);
          if (src.includes("<Icon")) for (const m of src.matchAll(/\[\s*"([a-z0-9_]+)",/g)) used.add(m[1]);
        }
    }
  };
  walk(path.join(root, "src"));
  const map = {};
  for (const n of [...used].sort()) {
    const file = path.join(root, "node_modules/@material-symbols/svg-500/rounded", `${n}.svg`);
    if (!fs.existsSync(file)) continue;
    const svg = fs.readFileSync(path.join(root, "node_modules/@material-symbols/svg-500/rounded", `${n}.svg`), "utf8");
    map[n] = svg.match(/ d="([^"]+)"/)[1];
  }
  fs.writeFileSync(path.join(root, "src/lib/icons.generated.js"), `// generated by tools/build.mjs\nexport default ${JSON.stringify(map, null, 1)};\n`);
}

const pages = Object.entries(cfg.pages);
const abs = (p) => path.join(root, p).replace(/\\/g, "/");

// 1. Generate per-page server + client entries
for (const [key, page] of pages) {
  const imports = `import React from "react";\nimport Page from "${abs(page.entry)}";\nimport { Layout } from "${abs("src/app/layout.jsx")}";\n`;
  fs.writeFileSync(
    path.join(tmp, `server-${key}.jsx`),
    `${imports}import { renderToString } from "react-dom/server";\nexport function render() { return renderToString(<Layout><Page /></Layout>); }\n`
  );
  fs.writeFileSync(
    path.join(tmp, `${key}.jsx`),
    `${imports}import { hydrateRoot } from "react-dom/client";\nhydrateRoot(document.getElementById("root"), <Layout><Page /></Layout>);\n`
  );
}

const shared = {
  bundle: true,
  jsx: "automatic",
  loader: { ".js": "jsx", ".jsx": "jsx", ".json": "json" },
  alias: { "@": path.join(root, "src") },
  logLevel: "warning",
  logOverride: { "unsupported-directive": "silent" },
  define: { "process.env.NODE_ENV": process.env.DEV ? '"development"' : '"production"' },
};

// 2. Server bundle (Node) and client bundle (browser, code-split)
await build({
  ...shared,
  entryPoints: pages.map(([k]) => path.join(tmp, `server-${k}.jsx`)),
  outdir: path.join(tmp, "server"),
  platform: "node",
  format: "esm",
  packages: "external",
});
await build({
  ...shared,
  entryPoints: pages.map(([k]) => path.join(tmp, `${k}.jsx`)),
  outdir: path.join(root, "assets/js"),
  platform: "browser",
  format: "esm",
  splitting: true,
  minify: !process.env.DEV,
  target: ["es2020"],
  entryNames: "[name]",
  chunkNames: "chunk-[hash]",
});

// 3. CSS via Tailwind v4
execFileSync(
  process.execPath,
  [path.join(root, "node_modules/@tailwindcss/cli/dist/index.mjs"), "-i", "src/styles.css", "-o", "assets/css/site.css", "--minify"],
  { stdio: "inherit" }
);

// 4. Static assets
fs.mkdirSync(path.join(root, "assets/fonts"), { recursive: true });
for (const f of fs.readdirSync(path.join(root, "reference/fonts"))) {
  if (/(inter|manrope)-(400|500|600|700)\.woff2$/.test(f))
    fs.copyFileSync(path.join(root, "reference/fonts", f), path.join(root, "assets/fonts", f));
}

// 5. Structured data
const addr = { "@type": "PostalAddress", ...cfg.address };
const org = {
  "@context": "https://schema.org",
  "@type": "ProfessionalService",
  "@id": `${base}/#business`,
  name: cfg.name,
  legalName: cfg.legalName,
  description: cfg.description,
  url: `${base}/`,
  logo: `${base}/assets/logo.svg`,
  image: `${base}/${cfg.ogImage}`,
  telephone: cfg.telephone,
  email: cfg.email,
  address: addr,
  areaServed: cfg.areasServed.map((n) => ({ "@type": "Place", name: n })),
  founder: { "@type": "Person", name: cfg.contactPerson },
  ...(cfg.abn ? { taxID: cfg.abn } : {}),
  ...(cfg.sameAs.length ? { sameAs: cfg.sameAs } : {}),
  hasOfferCatalog: {
    "@type": "OfferCatalog",
    name: "Technology services",
    itemListElement: [
      ["Cloud Architecture & Migration", "services/cloud-architecture-migration/"],
      ["Custom Software Development", "services/custom-software-development/"],
      ["DevOps & Automation", "services/devops-automation/"],
      ["Managed Cloud & Support", "services/#managed-cloud"],
      ["Cloud Security & Compliance", "services/#cloud-security"],
      ["Technical Consulting", "services/#consulting"],
    ].map(([name, p]) => ({ "@type": "Offer", itemOffered: { "@type": "Service", name, url: `${base}/${p}` } })),
  },
};

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

// 6. Render pages
for (const [key, page] of pages) {
  globalThis.__DYC_PAGE__ = page.path;
  const mod = await import(pathToFileURL(path.join(tmp, "server", `server-${key}.js`)).href + `?v=${version}`);
  const body = mod.render();
  const depth = page.path.split("/").filter(Boolean).length;
  const rel = depth ? "../".repeat(depth) : "./";
  const url = `${base}/${page.path}`;
  const crumbs =
    depth > 0
      ? {
          "@context": "https://schema.org",
          "@type": "BreadcrumbList",
          itemListElement: [
            { "@type": "ListItem", position: 1, name: "Home", item: `${base}/` },
            ...(depth > 1 ? [{ "@type": "ListItem", position: 2, name: "Services", item: `${base}/services/` }] : []),
            { "@type": "ListItem", position: depth > 1 ? 3 : 2, name: page.title.split(" | ")[0], item: url },
          ],
        }
      : null;
  const ld = [org, crumbs, ...(page.jsonld || [])].filter(Boolean);
  const html = `<!doctype html>
<html lang="en-AU">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(page.title)}</title>
<meta name="description" content="${esc(page.description)}">
<link rel="canonical" href="${url}">
<meta name="robots" content="index, follow">
<meta name="theme-color" content="#1b4f72">
<meta property="og:type" content="website">
<meta property="og:site_name" content="${esc(cfg.name)}">
<meta property="og:locale" content="en_AU">
<meta property="og:title" content="${esc(page.title)}">
<meta property="og:description" content="${esc(page.description)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${base}/${cfg.ogImage}">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="${rel}assets/favicon.svg" type="image/svg+xml">
<link rel="preload" href="${rel}assets/fonts/inter-400.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="${rel}assets/fonts/manrope-500.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="${rel}assets/css/site.css?v=${version}">
${ld.map((o) => `<script type="application/ld+json">${JSON.stringify(o).replace(/</g, "\\u003c")}</script>`).join("\n")}
</head>
<body class="antialiased scheme-1">
<a href="#main" class="sr-only focus:not-sr-only focus:fixed focus:top-2 focus:left-2 focus:z-[1000] focus:rounded-button focus:bg-white focus:px-4 focus:py-2">Skip to content</a>
<div id="root">${body}</div>
<script>window.__DYC_PAGE__=${JSON.stringify(page.path)};</script>
<script type="module" src="${rel}assets/js/${key}.js?v=${version}"></script>
</body>
</html>
`;
  const out = path.join(root, page.path, "index.html");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  console.log("built", "/" + page.path);
}

// 7. SEO + hosting files
const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(
  path.join(root, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages
    .map(([, p]) => `  <url><loc>${base}/${p.path}</loc><lastmod>${today}</lastmod></url>`)
    .join("\n")}\n</urlset>\n`
);
fs.writeFileSync(
  path.join(root, "robots.txt"),
  `User-agent: *\nAllow: /\nDisallow: /reference/\nDisallow: /src/\nDisallow: /tools/\nDisallow: /.build/\n\nSitemap: ${base}/sitemap.xml\n`
);
fs.writeFileSync(
  path.join(root, "llms.txt"),
  `# ${cfg.name}\n\n> ${cfg.description}\n\nContact: ${cfg.telephoneDisplay} · ${cfg.email}\nLocation: ${cfg.address.addressLocality} ${cfg.address.addressRegion}, Australia\n\n## Pages\n${pages
    .map(([, p]) => `- [${p.title.split(" | ")[0]}](${base}/${p.path}): ${p.description}`)
    .join("\n")}\n`
);
fs.writeFileSync(path.join(root, ".nojekyll"), "");
// 404 page (served by GitHub Pages at any depth, so it uses absolute URLs)
fs.writeFileSync(
  path.join(root, "404.html"),
  `<!doctype html>
<html lang="en-AU">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Page not found | ${esc(cfg.name)}</title>
<meta name="robots" content="noindex">
<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/assets/css/site.css?v=${version}">
</head>
<body class="antialiased scheme-1">
<main class="flex min-h-screen items-center px-[5%] py-16">
  <div class="container max-w-lg">
    <a href="/" aria-label="DYC Projects home"><img src="/assets/logo.svg" alt="DYC Projects" width="220" height="40"></a>
    <p class="mt-12 mb-3 font-semibold">Error 404</p>
    <h1 class="mb-5 text-h2 font-bold">Page not found</h1>
    <p class="text-medium">The page you are looking for has moved or no longer exists.</p>
    <div class="mt-8 flex flex-wrap gap-4">
      <a href="/" data-slot="button" class="inline-flex items-center justify-center rounded-button border border-blumine bg-blumine px-4 py-2 font-medium text-white hover:bg-blumine-dark">Go to the home page</a>
      <a href="/contact/" class="inline-flex items-center justify-center rounded-button border border-neutral-darkest-15 px-4 py-2 font-medium hover:bg-neutral-darkest-5">Contact us</a>
    </div>
  </div>
</main>
</body>
</html>
`
);
fs.rmSync(tmp, { recursive: true, force: true });
console.log("done");
